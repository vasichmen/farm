use RuntimeException;

class ProductSeeder extends Seeder
{
    public function run(): void
    {
        /** @var Collection<string, Category> $categories */
        $categories = CategoryRepository::query()->cacheFor(false)->get()->keyBy('name');
        /** @var Collection<string, Season> $seasons */
        $seasons = SeasonRepository::query()->cacheFor(false)->get()->keyBy('slug');

        foreach ($this->products() as $productData) {
            $category = $categories->get($productData['category']);

            if (! $category instanceof Category) {
                throw new RuntimeException("Не найдена категория {$productData['category']}.");
            }

            $seasonSettings = collect($productData['seasons']);
            $values = Arr::except($productData, ['seasons', 'category']);
            $values['category_id'] = $category->id;

            $product = ProductRepository::updateOrCreate(
                ['slug' => Product::makeSlug($productData['name'])],
                $values,
            );

            $pivot = $seasonSettings->mapWithKeys(
                static function (array $settings, string $seasonSlug) use ($seasons): array {
                    $season = $seasons->get($seasonSlug);

                    if (! $season instanceof Season) {
                        throw new RuntimeException("Не найден сезон {$seasonSlug}.");
                    }

                    return [$season->id => $settings];
                },
            );

            ProductRepository::syncSeasons($product->id, $pivot->all());
        }
    }

